const fs = require('fs');
const path = require('path');
const { Client, types } = require('./.db-migrate-deps/node_modules/pg');

// PostgreSQL DATE values must stay date-only. Parsing them as local midnight
// and serializing to UTC can otherwise move summer dates to the previous day.
types.setTypeParser(1082, (value) => value);

const outputDir = path.resolve(__dirname, '..', 'backups', 'supabase-migration-2026-07-27');

function quoteIdent(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function quoteLiteral(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function quoteRole(value) {
  return String(value).toLowerCase() === 'public' ? 'public' : quoteIdent(value);
}

function parsePgArray(value) {
  if (Array.isArray(value)) return value;
  if (!value) return [];
  const text = String(value);
  if (!text.startsWith('{') || !text.endsWith('}')) return [text];
  return text
    .slice(1, -1)
    .split(',')
    .map((item) => item.replace(/^"(.*)"$/, '$1').replaceAll('\\"', '"'));
}

async function connect() {
  const client = new Client({
    host: process.env.PGHOST,
    port: Number(process.env.PGPORT || 5432),
    user: process.env.PGUSER,
    password: process.env.PGPASSWORD,
    database: process.env.PGDATABASE || 'postgres',
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 10000,
  });
  await client.connect();
  await client.query('set role postgres');
  return client;
}

async function exportDatabase() {
  fs.mkdirSync(outputDir, { recursive: true });
  const client = await connect();

  const tableResult = await client.query(`
    select
      c.oid,
      c.relname as table_name,
      c.relrowsecurity as rls_enabled,
      c.relforcerowsecurity as rls_forced
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r'
    order by c.relname
  `);

  const enumResult = await client.query(`
    select t.typname, e.enumlabel, e.enumsortorder
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    join pg_enum e on e.enumtypid = t.oid
    where n.nspname = 'public'
    order by t.typname, e.enumsortorder
  `);

  const sequenceResult = await client.query(`
    select
      c.relname as sequence_name,
      s.seqstart,
      s.seqincrement,
      s.seqmin,
      s.seqmax,
      s.seqcache,
      s.seqcycle
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    join pg_sequence s on s.seqrelid = c.oid
    where n.nspname = 'public'
    order by c.relname
  `);

  const functionResult = await client.query(`
    select pg_get_functiondef(p.oid) as definition
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
    order by p.proname, p.oid
  `);

  const schema = [
    '-- Apartmani Balent: public schema export',
    'begin;',
    'set check_function_bodies = false;',
    '',
  ];

  const enums = new Map();
  for (const row of enumResult.rows) {
    if (!enums.has(row.typname)) enums.set(row.typname, []);
    enums.get(row.typname).push(row.enumlabel);
  }
  for (const [name, labels] of enums) {
    schema.push(`create type public.${quoteIdent(name)} as enum (${labels.map(quoteLiteral).join(', ')});`);
  }
  if (enums.size) schema.push('');

  for (const sequence of sequenceResult.rows) {
    schema.push(
      `create sequence public.${quoteIdent(sequence.sequence_name)}` +
      ` start with ${sequence.seqstart}` +
      ` increment by ${sequence.seqincrement}` +
      ` minvalue ${sequence.seqmin}` +
      ` maxvalue ${sequence.seqmax}` +
      ` cache ${sequence.seqcache}` +
      (sequence.seqcycle ? ' cycle;' : ' no cycle;')
    );
  }
  if (sequenceResult.rows.length) schema.push('');

  for (const table of tableResult.rows) {
    const columns = await client.query(`
      select
        a.attname as column_name,
        pg_catalog.format_type(a.atttypid, a.atttypmod) as data_type,
        a.attnotnull as not_null,
        pg_get_expr(ad.adbin, ad.adrelid) as default_value,
        a.attidentity as identity_kind,
        a.attgenerated as generated_kind
      from pg_attribute a
      left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
      where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped
      order by a.attnum
    `, [table.oid]);

    const definitions = columns.rows.map((column) => {
      let definition = `${quoteIdent(column.column_name)} ${column.data_type}`;
      if (column.identity_kind === 'a') definition += ' generated always as identity';
      if (column.identity_kind === 'd') definition += ' generated by default as identity';
      if (column.generated_kind === 's' && column.default_value) {
        definition += ` generated always as (${column.default_value}) stored`;
      } else if (!column.identity_kind && column.default_value) {
        definition += ` default ${column.default_value}`;
      }
      if (column.not_null) definition += ' not null';
      return definition;
    });

    schema.push(`create table public.${quoteIdent(table.table_name)} (`);
    schema.push(`  ${definitions.join(',\n  ')}`);
    schema.push(');', '');
  }

  const constraints = await client.query(`
    select
      c.relname as table_name,
      con.conname as constraint_name,
      pg_get_constraintdef(con.oid, true) as definition
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
    order by c.relname, con.conname
  `);
  for (const constraint of constraints.rows) {
    schema.push(
      `alter table public.${quoteIdent(constraint.table_name)}` +
      ` add constraint ${quoteIdent(constraint.constraint_name)} ${constraint.definition};`
    );
  }
  schema.push('');

  const indexes = await client.query(`
    select indexdef
    from pg_indexes i
    where i.schemaname = 'public'
      and not exists (
        select 1
        from pg_constraint c
        where c.conindid = (quote_ident(i.schemaname) || '.' || quote_ident(i.indexname))::regclass
      )
    order by i.tablename, i.indexname
  `);
  for (const index of indexes.rows) schema.push(`${index.indexdef};`);
  if (indexes.rows.length) schema.push('');

  for (const fn of functionResult.rows) schema.push(`${fn.definition};`, '');

  const triggers = await client.query(`
    select pg_get_triggerdef(t.oid, true) as definition
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
    order by c.relname, t.tgname
  `);
  for (const trigger of triggers.rows) schema.push(`${trigger.definition};`);
  if (triggers.rows.length) schema.push('');

  for (const table of tableResult.rows) {
    if (table.rls_enabled) {
      schema.push(`alter table public.${quoteIdent(table.table_name)} enable row level security;`);
    }
    if (table.rls_forced) {
      schema.push(`alter table public.${quoteIdent(table.table_name)} force row level security;`);
    }
  }
  schema.push('');

  const policies = await client.query(`
    select
      tablename,
      policyname,
      permissive,
      roles,
      cmd,
      qual,
      with_check
    from pg_policies
    where schemaname = 'public'
    order by tablename, policyname
  `);
  for (const policy of policies.rows) {
    const roles = parsePgArray(policy.roles).map(quoteRole).join(', ');
    let statement =
      `create policy ${quoteIdent(policy.policyname)} on public.${quoteIdent(policy.tablename)}` +
      ` as ${String(policy.permissive).toLowerCase() === 'permissive' ? 'permissive' : 'restrictive'}` +
      ` for ${String(policy.cmd).toLowerCase()} to ${roles}`;
    if (policy.qual) statement += ` using (${policy.qual})`;
    if (policy.with_check) statement += ` with check (${policy.with_check})`;
    schema.push(`${statement};`);
  }
  schema.push('');

  const grants = await client.query(`
    select table_name, grantee, privilege_type
    from information_schema.role_table_grants
    where table_schema = 'public'
      and grantee in ('anon', 'authenticated', 'service_role')
    order by table_name, grantee, privilege_type
  `);
  const groupedGrants = new Map();
  for (const grant of grants.rows) {
    const key = `${grant.table_name}\u0000${grant.grantee}`;
    if (!groupedGrants.has(key)) groupedGrants.set(key, []);
    groupedGrants.get(key).push(grant.privilege_type);
  }
  for (const [key, privileges] of groupedGrants) {
    const [tableName, grantee] = key.split('\u0000');
    schema.push(
      `grant ${privileges.join(', ')} on table public.${quoteIdent(tableName)} to ${quoteRole(grantee)};`
    );
  }

  schema.push('', 'commit;', '');
  fs.writeFileSync(path.join(outputDir, 'public-schema.sql'), schema.join('\n'), 'utf8');

  const data = {};
  for (const table of tableResult.rows) {
    const result = await client.query(`select * from public.${quoteIdent(table.table_name)}`);
    data[table.table_name] = result.rows;
  }
  fs.writeFileSync(path.join(outputDir, 'public-data.json'), JSON.stringify(data, null, 2), 'utf8');

  const manifest = {
    exportedAt: new Date().toISOString(),
    sourceHost: process.env.PGHOST,
    tables: Object.fromEntries(Object.entries(data).map(([name, rows]) => [name, rows.length])),
    databaseObjects: {
      enums: enums.size,
      sequences: sequenceResult.rows.length,
      functions: functionResult.rows.length,
      triggers: triggers.rows.length,
      policies: policies.rows.length,
      grants: grants.rows.length,
    },
  };
  fs.writeFileSync(path.join(outputDir, 'manifest.json'), JSON.stringify(manifest, null, 2), 'utf8');

  await client.end();
  console.log(`Exported ${tableResult.rows.length} tables to ${outputDir}`);
}

exportDatabase().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
